import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import AxeBuilder from '@axe-core/playwright';
const browser=await chromium.launch({headless:true,channel:'chrome'});
try {
  const context=await browser.newContext({viewport:{width:1512,height:1000},reducedMotion:'reduce'});
  const page=await context.newPage();
  await page.goto('http://localhost:3000',{waitUntil:'networkidle'});
  await page.locator('.appearance-sidebar [data-open="accessibility-dialog"]').click();
  await page.getByRole('switch',{name:'Focus on the article'}).check();
  await page.getByRole('button',{name:'Close accessibility menu'}).click();
  await page.waitForFunction(()=>document.activeElement.dataset.open==='accessibility-dialog' && document.activeElement.getClientRects().length>0);
  assert.equal(await page.evaluate(()=>document.activeElement.dataset.open==='accessibility-dialog' && document.activeElement.getClientRects().length>0),true,'Focus must follow a visible accessibility control when sidebars disappear.');
  await page.keyboard.press('Enter');
  await page.getByRole('button',{name:'Reset all',exact:true}).click();
  await page.getByRole('button',{name:'Close accessibility menu'}).click();
  await page.waitForFunction(()=>document.activeElement===document.querySelector('.appearance-sidebar [data-open="accessibility-dialog"]'));
  assert.equal(await page.locator('.appearance-sidebar [data-open="accessibility-dialog"]').evaluate(e=>e===document.activeElement),true,'Focus must return to the sidebar after leaving focus mode.');
  await page.emulateMedia({colorScheme:'dark'});
  await page.locator('.appearance-sidebar input[value="auto"]').check();
  assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
  await page.emulateMedia({colorScheme:'light'});
  await page.waitForFunction(()=>document.documentElement.dataset.theme==='light');
  assert.equal(await page.locator('html').getAttribute('data-theme'),'light');
  await page.locator('.appearance-sidebar input[value="wide"]').check();
  assert.equal(await page.locator('html').getAttribute('data-width'),'wide');
  await page.locator('.appearance-sidebar [data-reset-appearance]').click();
  console.log('Focus recovery and live system color changes passed.');
  await page.locator('.contents-sidebar [data-hide]').click();
  assert.equal(await page.locator('#desktop-contents').isVisible(),false);
  await page.locator('.contents-sidebar [data-show]').click();
  assert.equal(await page.locator('#desktop-contents').isVisible(),true);
  await page.locator('.contents-sidebar a[href="#References"]').click();
  await page.getByRole('searchbox',{name:'Search references',exact:true}).fill('no-source-will-match-this');
  const referenceId=await page.locator('[data-reference="1"]').getAttribute('id');
  await page.locator(`sup.reference a[href="#${referenceId}"]`).first().click();
  assert.equal(await page.getByRole('searchbox',{name:'Search references',exact:true}).inputValue(),'');
  assert.equal(await page.locator('[data-reference]:visible').count(),99);
  assert.equal(await page.locator('[data-reference="1"]').evaluate(e=>e===document.activeElement),true);
  await page.locator('.back-to-top').click();
  await page.locator('.tools-menu summary').click();
  for(const label of ['Related changes','Upload file','Permanent link','Download as PDF','Printable version','Wikidata item']) assert.equal(await page.locator('.tools-menu').getByRole('link',{name:label,exact:true}).isVisible(),true);
  await page.locator('.tools-menu summary').click();
  await page.locator('.contents-sidebar a[href="#References"]').click();
  const refAudit=await new AxeBuilder({page}).include('#reference-table').withTags(['wcag2a','wcag2aa','wcag21a','wcag21aa','wcag22aa']).analyze();
  assert.equal(refAudit.violations.length,0,'The final reference presentation must have no automated accessibility violations.');
  assert.equal(await page.locator('.citation-primary').evaluateAll(links=>links.some(a=>a.getBoundingClientRect().height<44)),false);
  await page.screenshot({path:'test-results/references.png'});
  console.log('Additional interaction checks passed: focus-mode recovery, system theme, wide view, hide/show controls, filtered citation navigation, and complete tools menu.');
} catch(error) { console.error(error.message); throw error; }
finally { await browser.close(); }
